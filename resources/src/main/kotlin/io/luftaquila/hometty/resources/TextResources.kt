fun Context.text(key: String): String = TextResources.ids[key]?.let { getString(it) } ?: key

fun Context.message(error: Throwable): String =
    if (error is io.luftaquila.hometty.core.UserMessage) {
        val id =
            requireNotNull(TextResources.ids[error.key]) { "Missing translation: ${error.key}" }
        getString(id, *error.arguments)
    } else text(error.message ?: "message_operation_failed")

fun Context.choiceLabel(value: String): String =
    TextResources.ids["choice_$value"]?.let { getString(it) } ?: value
